def find_entry(title: str) -> CatalogEntry | None:
    key = normalize(title)
    return next((e for e in CATALOG if key in e.keys), None)


def map_entries() -> tuple[CatalogEntry, ...]:
    return tuple(e for e in CATALOG if e.from_map)
